def _format_datetime_wib(value: Any) -> str:
    """Render UTC run timestamps in Asia/Jakarta without guessing missing timestamps."""
    if value is None or value == "":
        return "—"
    candidate = value
    if isinstance(candidate, str):
        try:
            candidate = datetime.fromisoformat(candidate.replace("Z", "+00:00"))
        except ValueError:
            return str(value)
    if not isinstance(candidate, datetime):
        return str(candidate)
    if candidate.tzinfo is None:
        candidate = candidate.replace(tzinfo=timezone.utc)
    return candidate.astimezone(timezone(timedelta(hours=7))).strftime("%d %b %Y, %H:%M WIB")


def _base_join_sql() -> str:
    return """
        FROM jobs j
        LEFT JOIN companies c ON c.id = j.company_id
        LEFT JOIN job_sources s ON s.id = j.source_id
        LEFT JOIN job_matches jm
            ON jm.job_id = j.id AND jm.profile_id = %s
    """


def _build_job_filter_clause(
    search: str = "",
    source: str = "",
    eligibility: str = "",
    min_score: int = 0,
) -> tuple[str, list[Any]]:
    """Return the shared parameterized WHERE clause for list and count queries."""
    conditions: list[str] = []
    params: list[Any] = []

    if search:
        conditions.append(
            "(LOWER(j.title) LIKE %s OR LOWER(COALESCE(c.name, '')) LIKE %s "
            "OR LOWER(COALESCE(j.location, '')) LIKE %s)"
        )
        term = f"%{search.strip().lower()}%"
        params.extend([term, term, term])

    if source:
        conditions.append("s.name = %s")
        params.append(source)

    if eligibility:
        conditions.append("jm.eligibility_status = %s")
        params.append(eligibility)

    conditions.append("COALESCE(jm.overall_score, 0) >= %s")
    params.append(min_score)

    return (" WHERE " + " AND ".join(conditions)) if conditions else "", params


def build_job_query(
    profile_id: int | None,
    search: str = "",
    source: str = "",
    eligibility: str = "",
    min_score: int = 0,
    limit: int = PAGE_SIZE,
    offset: int = 0,
    sort_by: str = "score",
) -> tuple[str, list[Any]]:
    """Build the paginated job query using the latest per-profile score row."""
    sql = """
        SELECT
            j.id,
            j.title,
            COALESCE(c.name, 'Unknown company') AS company_name,
            COALESCE(s.name, 'Unknown source') AS source_name,
            COALESCE(j.location, 'Unspecified') AS location,
            COALESCE(j.country, '') AS country,
            j.workplace_type,
            j.job_url,
            j.posted_at,
            j.closing_at,
            j.status AS job_status,
            jm.overall_score,
            jm.skill_score,
            jm.role_score,
            jm.location_score,
            jm.eligibility_status,
            jm.reasoning,
            jm.scored_at
    """ + _base_join_sql()

    where_sql, filter_params = _build_job_filter_clause(
        search=search,
        source=source,
        eligibility=eligibility,
        min_score=min_score,
    )
    sql += where_sql

    sort_by = sort_by if sort_by in {"score", "newest", "posted"} else "score"
    if sort_by == "newest":
        # jobs.id is AUTO_INCREMENT and therefore the reliable insertion-order proxy
        # available in the existing schema; no destructive migration is required.
        sql += " ORDER BY j.id DESC, jm.overall_score IS NULL ASC, jm.overall_score DESC"
    elif sort_by == "posted":
        sql += " ORDER BY j.posted_at IS NULL ASC, j.posted_at DESC, jm.overall_score IS NULL ASC, jm.overall_score DESC, j.id DESC"
    else:
        # Overall score is the primary sort. Location is only a tie-breaker.
        sql += """
            ORDER BY
                jm.overall_score IS NULL ASC,
                jm.overall_score DESC,
                CASE jm.eligibility_status
                    WHEN 'australia_listed' THEN 1
                    WHEN 'singapore_listed' THEN 2
                    WHEN 'worldwide_claimed' THEN 3
                    WHEN 'remote_eligibility_unverified' THEN 4
                    WHEN 'location_restriction_review' THEN 5
                    WHEN 'location_not_matched' THEN 6
                    ELSE 99
                END ASC,
                j.posted_at DESC,
                j.id DESC
        """

    sql += " LIMIT %s OFFSET %s"
    params: list[Any] = [profile_id, *filter_params, max(1, min(int(limit), 500)), max(0, int(offset))]
    return sql, params


def build_application_query(
    profile_id: int | None,
    status: str = "",
    limit: int = PAGE_SIZE,
) -> tuple[str, list[Any]]:
    """Build a parameterized, read-only query for saved application drafts."""
    sql = """
        SELECT
            a.id AS application_id,
            a.job_id,
            a.profile_id,
            a.match_score,
            a.match_reason,
            a.application_status,
            a.cover_letter,
            a.applied_at,
            a.notes,
            j.title,
            COALESCE(c.name, 'Unknown company') AS company_name,
            COALESCE(j.country, '') AS country,
            COALESCE(j.location, 'Unspecified') AS location,
            j.job_url,
            jm.eligibility_status
        FROM applications a
        JOIN jobs j ON j.id = a.job_id
        LEFT JOIN companies c ON c.id = j.company_id
        LEFT JOIN job_matches jm
            ON jm.job_id = a.job_id AND jm.profile_id = a.profile_id
        WHERE a.profile_id = %s
    """
    params: list[Any] = [profile_id]
    if status:
        sql += " AND a.application_status = %s"
        params.append(status)
    sql += " ORDER BY a.id DESC LIMIT %s"
    params.append(limit)
    return sql, params


def _ensure_application_cover_letter_pdf(
    application_id: int,
    profile_id: int | None = None,
    *,
    force: bool = False,
) -> Path:
    """Create a professional local PDF for one saved application; never submits it."""
    with get_connection() as conn:
        cursor = conn.cursor(dictionary=True)
        try:
            active_profile_id = profile_id if profile_id is not None else _profile_id(cursor)
            if active_profile_id is None:
                raise ValueError("Profil aktif tidak ditemukan.")
            cursor.execute(
                """SELECT a.id AS application_id, a.profile_id, a.cover_letter,
                          COALESCE(j.title, 'Job application') AS job_title,
                          COALESCE(c.name, '') AS company_name
                   FROM applications a
                   JOIN jobs j ON j.id = a.job_id
                   LEFT JOIN companies c ON c.id = j.company_id
                   WHERE a.id = %s AND a.profile_id = %s
                   LIMIT 1""",
                (int(application_id), int(active_profile_id)),
            )
            row = cursor.fetchone()
        finally:
            cursor.close()

    if not row:
        raise ValueError("Aplikasi tidak ditemukan untuk profil aktif.")
    letter = str(row.get("cover_letter") or "").strip()
    if not letter:
        raise ValueError("Aplikasi ini belum memiliki isi cover letter.")

    project_root = Path(__file__).resolve().parent
    packet_dir = project_root / "application_packets" / f"application_{int(application_id)}"
    packet_dir.mkdir(parents=True, exist_ok=True)
    text_path = packet_dir / "cover_letter.txt"
    if not text_path.exists():
        text_path.write_text(letter + "\n", encoding="utf-8")
    pdf_path = packet_dir / "cover_letter.pdf"
    if force or not pdf_path.exists():
        build_cover_letter_pdf(
            pdf_path,
            letter,
            job_title=str(row.get("job_title") or ""),
            company_name=str(row.get("company_name") or ""),
        )
    return pdf_path


