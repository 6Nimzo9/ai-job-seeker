def determine_application_transition(
    action: str, current_status: str, applied_at: Any,
    has_cover_letter: bool, confirm_submitted: bool = False,
) -> tuple[str, str, bool]:
    """Validate an explicit review action. Returns (new_status, audit_note, set_applied_at).

    This helper never submits an application; mark_submitted only records a user's
    confirmation that they already submitted through the official application route.
    """
    status = str(current_status or "").strip().lower()
    if action == "approve":
        if status not in {"pending_approval", "draft_review", "draft"}:
            raise ValueError(f"Draf berstatus '{status or 'unknown'}' tidak dapat disetujui dari tahap ini.")
        if not has_cover_letter:
            raise ValueError("Draf tidak memiliki surat lamaran; tidak dapat disetujui.")
        return (
            "approved",
            "Manually approved for application review; dashboard did not submit the application.",
            False,
        )

    if action == "archive":
        if status in {"submitted", "applied"} or applied_at is not None:
            raise ValueError("Lamaran yang sudah tercatat terkirim tidak dapat diarsipkan dari tindakan ini.")
        if status == "archived":
            raise ValueError("Draf sudah diarsipkan.")
        return ("archived", "Archived manually by user; record retained and not deleted.", False)

    if action == "mark_submitted":
        if status != "approved":
            raise ValueError("Setujui draf terlebih dahulu sebelum mencatat pengiriman.")
        if applied_at is not None:
            raise ValueError("Tanggal pengiriman sudah tercatat; tidak ada perubahan.")
        if not confirm_submitted:
            raise ValueError("Centang konfirmasi bahwa lamaran benar-benar sudah dikirim melalui situs resmi.")
        return (
            "submitted",
            "Manually recorded as submitted by user; dashboard did not submit the application.",
            True,
        )

    raise ValueError("Tindakan tidak dikenal.")


