def _format_utc_offset(value: float) -> str:
    """Format a numeric UTC offset as UTC+7, UTC-3:30, etc."""
    total_minutes = int(round(abs(value) * 60))
    hours, minutes = divmod(total_minutes, 60)
    sign = "+" if value >= 0 else "−"
    return f"UTC{sign}{hours}" if minutes == 0 else f"UTC{sign}{hours}:{minutes:02d}"


def _humanize_location_detail(raw_detail: Any) -> str:
    """Translate scraped timezone metadata into plain Indonesian language."""
    raw = str(raw_detail or "").strip()
    if not raw:
        return ""

    pieces = re.split(r";\s*(?=(?:Timezone restrictions:|Title indicates|Description indicates))", raw, flags=re.IGNORECASE)
    friendly: list[str] = []
    for piece in pieces:
        part = piece.strip(" ;")
        if not part:
            continue
        tz_match = re.match(r"Timezone restrictions:\s*(.*)", part, flags=re.IGNORECASE | re.DOTALL)
        if tz_match:
            raw_offsets = tz_match.group(1)
            offset_tokens = re.findall(r"(?<![A-Za-z0-9])([+-]?\d+(?:\.\d+)?)(?![A-Za-z0-9])", raw_offsets)
            offsets: list[float] = []
            for token in offset_tokens:
                try:
                    val = float(token)
                    if -12 <= val <= 14 and val not in offsets:
                        offsets.append(val)
                except ValueError:
                    continue
            if offsets:
                lowest, highest = min(offsets), max(offsets)
                if math.isclose(lowest, highest):
                    range_text = _format_utc_offset(lowest)
                else:
                    range_text = f"{_format_utc_offset(lowest)} sampai {_format_utc_offset(highest)}"
                if any(math.isclose(value, 7.0) for value in offsets):
                    wib_note = "WIB Indonesia (Jakarta, UTC+7) termasuk dalam daftar zona waktu ini."
                else:
                    wib_note = "WIB Indonesia (Jakarta, UTC+7) tidak tercantum dalam daftar yang diberikan sumber."
                examples = (
                    "Contoh: Jakarta/WIB = UTC+7; Singapura = UTC+8; London = UTC+0; "
                    "New York biasanya UTC−5 dan dapat berubah saat daylight saving."
                )
                caution = "Catatan: zona waktu menunjukkan kesesuaian jam kerja, bukan jaminan perusahaan menerima pelamar dari Indonesia."
                friendly.append(f"Zona waktu yang dicantumkan iklan: {range_text}. {wib_note} {examples} {caution}")
            else:
                friendly.append("Sumber lowongan mencantumkan catatan zona waktu, tetapi format angkanya tidak dapat dibaca otomatis. Periksa deskripsi resmi lowongan.")
        elif re.match(r"Title indicates:?", part, flags=re.IGNORECASE):
            value = re.sub(r"^Title indicates:?\s*", "", part, flags=re.IGNORECASE).strip()
            if value:
                friendly.append(f"Petunjuk dari judul lowongan: {value}.")
        elif re.match(r"Description indicates:?", part, flags=re.IGNORECASE):
            value = re.sub(r"^Description indicates:?\s*", "", part, flags=re.IGNORECASE).strip()
            if value:
                friendly.append(f"Petunjuk dari deskripsi lowongan: {value}.")
        else:
            friendly.append(part)
    return " ".join(friendly)


def _manual_n8n_settings() -> tuple[str, str, bool]:
    """Read webhook settings and allow calls only to a local n8n instance."""
    webhook_url = os.getenv("N8N_MANUAL_WEBHOOK_URL", DEFAULT_N8N_MANUAL_WEBHOOK_URL).strip()
    token = os.getenv("N8N_MANUAL_WEBHOOK_TOKEN", "").strip()
    try:
        parsed = urlparse(webhook_url)
        safe_host = (parsed.hostname or "").lower() in {"127.0.0.1", "localhost", "::1"}
        safe_port = parsed.port in (None, 5678)
        safe_scheme = parsed.scheme in {"http", "https"}
        safe_path = parsed.path.startswith("/webhook/")
        safe_url = bool(safe_host and safe_port and safe_scheme and safe_path)
    except ValueError:
        safe_url = False
    placeholder = token.lower() in {"replace-me", "replace-with-a-token", "your-token", "changeme", "ganti_dengan_token_yang_sama", "paste_the_same_header_auth_token_here"}
    ready = bool(safe_url and len(token) >= 16 and not placeholder)
    return webhook_url, token, ready


