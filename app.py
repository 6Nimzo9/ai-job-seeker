@app.post("/jobs/<int:job_id>/queue")
def queue_job(job_id: int):
    """Add/remove a job from the personal shortlist shown inside Review Center."""
    provided_token = request.form.get("csrf_token", "")
    expected_token = session.get("_csrf_token", "")
    if not expected_token or not provided_token or not hmac.compare_digest(provided_token, expected_token):
        flash("Permintaan ditolak karena token keamanan tidak valid. Muat ulang halaman.", "error")
        return redirect(url_for("jobs_page"))

    action = request.form.get("action", "add").strip().lower()
    return_to = request.form.get("return_to", "jobs").strip().lower()
    conn = None
    cursor = None
    try:
        conn = get_connection()
        cursor = conn.cursor(dictionary=True)
        ensure_review_queue_table(cursor)
        profile_id = _profile_id(cursor)
        if profile_id is None:
            raise ValueError("Profil aktif tidak ditemukan; pilihan tidak disimpan.")

        cursor.execute("SELECT id FROM jobs WHERE id = %s", (job_id,))
        if not cursor.fetchone():
            raise ValueError("Lowongan tidak ditemukan di database.")

        if action == "remove":
            cursor.execute(
                "DELETE FROM job_review_queue WHERE profile_id = %s AND job_id = %s",
                (profile_id, job_id),
            )
            conn.commit()
            flash("Lowongan dihapus dari daftar pilihan saja. Data lowongan, skor, dan draf lamaran tetap tersimpan.", "success")
        elif action == "add":
            # The shortlist and saved application drafts are independent lists.
            # A job may legitimately exist in both, so never suppress queue insertion
            # merely because applications already contains a draft for this job.
            cursor.execute(
                """INSERT INTO job_review_queue (profile_id, job_id, queue_status)
                   VALUES (%s, %s, 'selected')
                   ON DUPLICATE KEY UPDATE queue_status = 'selected'""",
                (profile_id, job_id),
            )
            conn.commit()
            flash("Lowongan ditambahkan ke daftar pilihan Review Center. Data draf yang sudah ada tetap dipertahankan.", "success")
        else:
            raise ValueError("Tindakan pilihan lowongan tidak dikenal.")
    except ValueError as exc:
        if conn:
            conn.rollback()
        flash(str(exc), "error")
    except Exception:
        if conn:
            conn.rollback()
        logger.exception("Job review queue action failed")
        flash("Pilihan lowongan tidak berhasil diperbarui. Periksa terminal untuk detail.", "error")
    finally:
        if cursor is not None:
            try:
                cursor.close()
            except Exception:
                pass
        if conn is not None:
            try:
                conn.close()
            except Exception:
                pass

    if return_to == "review":
        return redirect(url_for("review_page"))
    return redirect(url_for(
        "jobs_page",
        q=request.form.get("q", "").strip()[:150],
        source=request.form.get("source", "").strip()[:100],
        eligibility=request.form.get("eligibility", "").strip()[:100],
        min_score=_int_arg(request.form.get("min_score"), 0, 0, 100),
        jobs_page=_int_arg(request.form.get("jobs_page"), 1, 1, 100000),
        jobs_sort=request.form.get("jobs_sort", "score").strip().lower()[:20],
    ))


@app.post("/review/jobs/<int:job_id>/create-draft")
def create_job_draft(job_id: int):
    """Generate and save one AI cover-letter draft for a selected job; never submit it."""
    provided_token = request.form.get("csrf_token", "")
    expected_token = session.get("_csrf_token", "")
    if not expected_token or not provided_token or not hmac.compare_digest(provided_token, expected_token):
        flash("Permintaan ditolak karena token keamanan tidak valid. Muat ulang halaman.", "error")
        return redirect(url_for("review_page"))

    conn = None
    cursor = None
    try:
        conn = get_connection()
        cursor = conn.cursor(dictionary=True)
        ensure_review_queue_table(cursor)
        profile_id = _profile_id(cursor)
        if profile_id is None:
            raise ValueError("Profil aktif tidak ditemukan; draf tidak dibuat.")

        cursor.execute(
            """SELECT j.id, j.title
               FROM job_review_queue q
               JOIN jobs j ON j.id = q.job_id
               WHERE q.profile_id = %s AND q.job_id = %s
                 AND q.queue_status = 'selected'
               LIMIT 1""",
            (profile_id, job_id),
        )
        selected = cursor.fetchone()
        if not selected:
            raise ValueError("Lowongan tidak lagi berada di daftar pilihan. Muat ulang Review Center.")

        cursor.execute(
            "SELECT id FROM applications WHERE profile_id = %s AND job_id = %s LIMIT 1",
            (profile_id, job_id),
        )
        existing_application = cursor.fetchone()
        if existing_application:
            raise ValueError(
                f"Lowongan ini sudah memiliki draf/catatan aplikasi ID {existing_application['id']}. "
                "Gunakan bagian Application Review untuk melihatnya."
            )

        project_root = os.path.dirname(os.path.abspath(__file__))
        generator_path = os.path.join(project_root, "application_generator.py")
        if not os.path.isfile(generator_path):
            raise ValueError("application_generator.py tidak ditemukan di folder proyek AI Job Seeker.")

        # Close this read connection before the generator opens its own transaction.
        cursor.close()
        cursor = None
        conn.close()
        conn = None

        try:
            result = subprocess.run(
                [sys.executable, generator_path, "--profile-id", str(int(profile_id)),
                 "--job-id", str(int(job_id)), "--min-score", "0", "--commit", "--manual-review-override"],
                cwd=project_root,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=210,
                check=False,
            )
        except subprocess.TimeoutExpired:
            flash(
                "Pembuatan draf melewati batas waktu 210 detik. Pastikan Ollama dan model aktif, lalu periksa Application Review sebelum mencoba lagi.",
                "error",
            )
            return redirect(url_for("review_page") + "#application-review")
        except OSError:
            logger.exception("Could not start the local application draft generator")
            flash("Generator draf tidak dapat dijalankan. Pastikan Python proyek dan application_generator.py tersedia.", "error")
            return redirect(url_for("review_page") + "#application-review")

        # Do not show or log the generated cover-letter text itself. Verify the real
        # database result rather than depending on console wording from generator versions.
        combined_output = (result.stdout or "") + "\n" + (result.stderr or "")
        saved_application = None
        verify_conn = None
        verify_cursor = None
        try:
            verify_conn = get_connection()
            verify_cursor = verify_conn.cursor(dictionary=True)
            verify_cursor.execute(
                "SELECT id FROM applications WHERE profile_id = %s AND job_id = %s LIMIT 1",
                (int(profile_id), int(job_id)),
            )
            saved_application = verify_cursor.fetchone()
        except Exception:
            logger.exception("Could not verify saved draft for job_id=%s", job_id)
        finally:
            if verify_cursor is not None:
                try:
                    verify_cursor.close()
                except Exception:
                    pass
            if verify_conn is not None:
                try:
                    verify_conn.close()
                except Exception:
                    pass

        if saved_application:
            # Remove from shortlist only after verifying the application was saved.
            cleanup_conn = None
            cleanup_cursor = None
            try:
                cleanup_conn = get_connection()
                cleanup_cursor = cleanup_conn.cursor()
                cleanup_cursor.execute(
                    "DELETE FROM job_review_queue WHERE profile_id = %s AND job_id = %s AND queue_status = 'selected'",
                    (int(profile_id), int(job_id)),
                )
                cleanup_conn.commit()
            except Exception:
                if cleanup_conn is not None:
                    try:
                        cleanup_conn.rollback()
                    except Exception:
                        pass
                logger.exception("Draft saved but review-queue cleanup failed for job_id=%s", job_id)
            finally:
                if cleanup_cursor is not None:
                    try:
                        cleanup_cursor.close()
                    except Exception:
                        pass
                if cleanup_conn is not None:
                    try:
                        cleanup_conn.close()
                    except Exception:
                        pass

            pdf_note = ""
            try:
                pdf_path = _ensure_application_cover_letter_pdf(int(saved_application["id"]), int(profile_id))
                pdf_note = f" PDF tersimpan di application_packets\\application_{int(saved_application['id'])}\\cover_letter.pdf."
            except Exception:
                logger.exception("Draft saved but cover-letter PDF generation failed for application_id=%s", saved_application["id"])
                pdf_note = " Draf tersimpan, tetapi PDF belum dibuat; periksa instalasi ReportLab."

            flash(
                f"Draf AI untuk lowongan #{job_id} berhasil dibuat dan disimpan sebagai aplikasi #{saved_application['id']}. Lamaran belum dikirim; tinjau isi draf di Application Review. Catatan: filter skor/lokasi otomatis dilewati karena kamu memilih lowongan ini secara manual; izin kerja dan sponsorship tetap perlu diperiksa." + pdf_note,
                "success",
            )
        elif "Tidak ada data kandidat yang dapat diproses untuk lowongan terpilih" in combined_output:
            flash(
                "Draf belum dibuat. Lowongan terpilih mungkin sudah ditutup, belum memiliki hasil scoring terbaru, deskripsinya kosong, atau tidak dapat dibaca. Filter lokasi dan skor otomatis sudah dilewati untuk pilihan manual ini; periksa terminal Dashboard untuk detailnya.",
                "error",
            )
        else:
            # CLAUD_DRAFT_FEEDBACK_DIAGNOSTICS_V1
            output_lines = [line.strip() for line in combined_output.splitlines() if line.strip()]

            # Surface generator validation blockers instead of hiding them behind a
            # generic Ollama/CV warning. The actual cover-letter body is never logged.
            review_flags = []
            in_review_flags = False
            for line in output_lines:
                if "--- REVIEW FLAGS ---" in line:
                    in_review_flags = True
                    continue
                if in_review_flags:
                    if line.startswith("Status:") or line.startswith("---"):
                        in_review_flags = False
                        continue
                    if line.startswith("-"):
                        flag = line.lstrip("- ").strip()
                        if flag and flag not in review_flags:
                            review_flags.append(flag)

            detail_lines = [
                line for line in output_lines
                if line.startswith("ERROR") or "Pastikan Ollama aktif" in line
            ]
            detail = (" ".join(detail_lines[-2:]))[:500]

            if review_flags:
                concise_flags = "; ".join(review_flags[:3])
                logger.warning(
                    "Draft quality validation blocked save for job_id=%s; flag_count=%s; flags=%s",
                    job_id, len(review_flags), concise_flags[:1000],
                )
                flash(
                    "Draf belum disimpan karena pemeriksaan kualitas cover letter menemukan: "
                    + concise_flags
                    + (" (dan masalah lainnya). Perbaiki profil/draf lalu coba lagi." if len(review_flags) > 3 else ". Perbaiki profil/draf lalu coba lagi."),
                    "error",
                )
            elif detail:
                logger.warning(
                    "Draft generator reported an error for job_id=%s, returncode=%s: %s",
                    job_id, result.returncode, detail,
                )
                flash("Draf gagal dibuat: " + detail, "error")
            elif result.returncode != 0:
                logger.warning(
                    "Draft generator exited abnormally for job_id=%s, returncode=%s; diagnostic output omitted to protect draft contents",
                    job_id, result.returncode,
                )
                flash(
                    f"Generator draf berhenti dengan kode {result.returncode}, tetapi tidak mengembalikan pesan kesalahan yang dapat dikenali. Periksa terminal Dashboard untuk traceback.",
                    "error",
                )
            else:
                logger.warning(
                    "Draft generator finished without a verified application row for job_id=%s, returncode=%s",
                    job_id, result.returncode,
                )
                flash(
                    "Generator selesai tetapi record aplikasi belum ditemukan di MySQL. Periksa log Dashboard dan tabel applications sebelum mencoba ulang.",
                    "error",
                )
    except ValueError as exc:
        if conn is not None:
            try:
                conn.rollback()
            except Exception:
                pass
        flash(str(exc), "error")
    except Exception:
        if conn is not None:
            try:
                conn.rollback()
            except Exception:
                pass
        logger.exception("Create job draft route failed for job_id=%s", job_id)
        flash("Permintaan pembuatan draf gagal. Periksa terminal dashboard untuk detail teknis.", "error")
    finally:
        if cursor is not None:
            try:
                cursor.close()
            except Exception:
                pass
        if conn is not None:
            try:
                conn.close()
            except Exception:
                pass

    return redirect(url_for("review_page") + "#application-review")


