@app.post("/automation/trigger")
def trigger_manual_n8n_workflow():
    """Run manual discovery+scoring and wait for n8n's final-node response."""
    return_page = request.form.get("return_to", "automation")
    destination = url_for("overview_page") if return_page == "overview" else url_for("automation_page")

    provided_token = request.form.get("csrf_token", "")
    expected_token = session.get("_csrf_token", "")
    if not expected_token or not provided_token or not hmac.compare_digest(provided_token, expected_token):
        flash("Permintaan ditolak karena token keamanan tidak valid. Muat ulang halaman.", "error")
        return redirect(destination)

    webhook_url, trigger_token, ready = _manual_n8n_settings()
    if not ready:
        flash(
            "Pemicu n8n belum siap. Periksa N8N_MANUAL_WEBHOOK_URL dan N8N_MANUAL_WEBHOOK_TOKEN pada file .env di D:\\AIJobSeeker.",
            "error",
        )
        return redirect(destination)

    # A second click must not launch another long-running manual execution.
    # The API also has a pipeline-wide lock shared by manual and daily workflows.
    if not MANUAL_TRIGGER_LOCK.acquire(blocking=False):
        flash("Workflow manual dari Dashboard masih berjalan. Tunggu sampai selesai sebelum menjalankannya lagi.", "error")
        return redirect(destination)

    try:
        payload = {
            "source": "ai-job-seeker-dashboard",
            "action": "discover_and_score",
            "triggered_at_utc": datetime.now(timezone.utc).isoformat(),
            "note": "Manual workflow is intended to run discovery and scoring only; no application submission.",
        }
        req = URLRequest(
            webhook_url,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json", N8N_TRIGGER_HEADER: trigger_token},
            method="POST",
        )
        # 100 employer board APIs are fetched with bounded concurrency. Allow
        # up to 10 minutes for the webhook to return its final scoring result.
        with urlopen(req, timeout=600) as response:
            status_code = int(response.status)
            response_body = response.read(32768).decode("utf-8", errors="replace")

        if 200 <= status_code < 300:
            try:
                response_data = json.loads(response_body) if response_body.strip() else {}
            except (TypeError, ValueError):
                response_data = {}

            # n8n's default Webhook mode responds immediately with this message.
            # Do not misrepresent that acknowledgement as a completed run.
            immediate_ack = "workflow got started" in response_body.lower()
            if immediate_ack:
                flash(
                    "n8n menerima permintaan, tetapi webhook masih merespons sebelum workflow selesai. "
                    "Pada node Webhook workflow manual, ubah Respond menjadi 'When Last Node Finishes' "
                    "dan Response Data menjadi 'First Entry JSON', lalu Publish.",
                    "error",
                )
            elif isinstance(response_data, dict) and response_data.get("success") is False:
                detail = str(response_data.get("error") or "Node terakhir melaporkan kegagalan.")[:350]
                flash(f"Workflow selesai dengan status gagal: {detail}", "error")
            else:
                output_text = ""
                if isinstance(response_data, dict):
                    output_text = str(response_data.get("output") or "")
                elif isinstance(response_data, list) and response_data and isinstance(response_data[0], dict):
                    item = response_data[0]
                    output_text = str(item.get("output") or item.get("json", {}).get("output") or "")

                total_match = re.search(r"Total lowongan dinilai:\s*(\d+)", output_text, flags=re.IGNORECASE)
                if total_match:
                    flash(
                        f"Selesai. Scoring terbaru berhasil dijalankan untuk {total_match.group(1)} lowongan. "
                        "Overview dimuat ulang dari MySQL.",
                        "success",
                    )
                else:
                    flash(
                        "Workflow discovery dan scoring telah selesai. Overview dimuat ulang dari MySQL.",
                        "success",
                    )
        else:
            flash(f"n8n menjawab HTTP {status_code}. Periksa Executions untuk detail kegagalan.", "error")

    except HTTPError as exc:
        logger.warning("n8n manual webhook returned HTTP %s", exc.code)
        try:
            error_body = exc.read(1200).decode("utf-8", errors="replace")
        except Exception:
            error_body = ""
        if exc.code in (401, 403):
            message = "n8n menolak permintaan. Pastikan token Dashboard sama dengan Header Auth pada node Webhook."
        elif exc.code == 404:
            message = "Webhook tidak ditemukan. Pastikan workflow manual sudah Published/Active dan URL path cocok."
        elif exc.code == 409:
            message = "Discovery atau scoring lain sedang berjalan (workflow manual/harian). Tunggu sampai selesai, lalu coba lagi."
        else:
            message = f"Workflow n8n gagal (HTTP {exc.code}). Periksa Executions di n8n."
        if error_body and exc.code not in (401, 403):
            logger.warning("n8n webhook error response: %s", error_body[:500])
        flash(message, "error")
    except (URLError, TimeoutError, OSError) as exc:
        logger.warning("n8n manual webhook could not be reached or timed out: %s", exc)
        flash(
            "Dashboard tidak menerima hasil akhir dalam 270 detik. Periksa Executions di n8n sebelum mencoba lagi; "
            "jangan klik ulang ketika execution sebelumnya masih berjalan.",
            "error",
        )
    except Exception:
        logger.exception("Manual n8n trigger failed")
        flash("Pemicu manual gagal. Periksa terminal Dashboard untuk detail teknis; token tidak ditampilkan.", "error")
    finally:
        MANUAL_TRIGGER_LOCK.release()

    return redirect(destination)

