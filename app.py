_INDONESIAN_MONTHS = (
    "Jan", "Feb", "Mar", "Apr", "Mei", "Jun",
    "Jul", "Agu", "Sep", "Okt", "Nov", "Des",
)

def _format_date_id(value: Any) -> str:
    """Format a date for the dashboard without guessing a missing date."""
    if value is None or value == "":
        return ""
    candidate = value
    if isinstance(candidate, str):
        text = candidate.strip()
        if not text:
            return ""
        try:
            candidate = datetime.fromisoformat(text.replace("Z", "+00:00"))
        except ValueError:
            try:
                candidate = date.fromisoformat(text[:10])
            except ValueError:
                return text
    if isinstance(candidate, datetime):
        candidate = candidate.date()
    if isinstance(candidate, date):
        return f"{candidate.day:02d} {_INDONESIAN_MONTHS[candidate.month - 1]} {candidate.year}"
    return str(candidate)


def _split_location_metadata(value: Any) -> tuple[str, str]:
    """Return a concise location label and keep verbose source metadata collapsed."""
    raw_location = str(value or "Unspecified").strip()
    parts = LOCATION_META_SPLIT.split(raw_location, maxsplit=1)
    display_location = parts[0].strip().rstrip(";") or "Unspecified"
    location_details = _humanize_location_detail(parts[1].strip()) if len(parts) > 1 else ""
    return display_location, location_details


