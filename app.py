def _delete_application_packet_files(application_id: int) -> bool:
    """Delete only application_packets/application_<id>, without following external symlinks."""
    project_root = Path(__file__).resolve().parent
    packet_root = project_root / "application_packets"
    if packet_root.is_symlink():
        raise OSError("Folder application_packets tidak boleh berupa symbolic link.")
    if not packet_root.exists():
        return False

    packet_dir = packet_root / f"application_{int(application_id)}"
    if packet_dir.is_symlink():
        # Unlink the link itself; never traverse its target.
        packet_dir.unlink()
        return True
    if not packet_dir.exists():
        return False

    resolved_root = packet_root.resolve()
    resolved_packet = packet_dir.resolve()
    if resolved_packet.parent != resolved_root:
        raise OSError("Lokasi packet di luar folder application_packets; penghapusan dibatalkan.")
    if resolved_packet.is_dir():
        shutil.rmtree(resolved_packet)
    else:
        resolved_packet.unlink()
    return True


